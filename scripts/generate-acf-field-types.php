<?php

/**
 * Regenerate `phpstan/acf-field-types.php` from the field group files in `assets/json/acf-json`.
 *
 *   php scripts/generate-acf-field-types.php            write the map
 *   php scripts/generate-acf-field-types.php --check    exit 1 when the committed map is out of date
 */

declare(strict_types=1);

use UamswpFindADoc\PhpStan\AcfFieldTypes;

require dirname(__DIR__).'/vendor/autoload.php';

$root = dirname(__DIR__);
$target = $root.'/phpstan/acf-field-types.php';
$types = AcfFieldTypes::fromDirectory($root.'/assets/json/acf-json');

$generated = "<?php\n\n/**\n * The type get_field() returns for each ACF field name. Generated by scripts/generate-acf-field-types.php from\n * assets/json/acf-json; do not edit by hand.\n */\n\ndeclare(strict_types=1);\n\nreturn [\n";

foreach ($types as $name => $type) {
    $generated .= sprintf("    '%s' => '%s',\n", $name, $type);
}

$generated .= "];\n";

if (in_array('--check', $argv, true)) {
    if (! is_file($target) || file_get_contents($target) !== $generated) {
        fwrite(STDERR, "phpstan/acf-field-types.php is out of date. Run: php scripts/generate-acf-field-types.php\n");
        exit(1);
    }

    echo count($types)." field types, map is current\n";
    exit(0);
}

file_put_contents($target, $generated);
echo 'Wrote '.count($types)." field types to phpstan/acf-field-types.php\n";
